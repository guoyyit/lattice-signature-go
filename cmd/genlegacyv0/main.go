//go:build genlegacyv0

// genlegacyv0 is a one-off, offline generator for fixed version-0 wire-format
// byte vectors. It is deliberately excluded from the normal build and test
// (//go:build ignore).
//
// It does NOT use the package's current writer to produce the samples: it
// re-implements the v0 envelope and payload layout directly from the format
// specification (see README "Versioning" and latticesig/legacy_v0.go). The
// current writer is used only as an *input decoder*: it round-trips live key
// material through the documented v1 payload layout so that the generator can
// read the coefficient values without depending on internal types.
//
// Run with:
//
//	go run -tags genlegacyv0 ./cmd/genlegacyv0
//
// Paste the emitted hex constants into latticesig/legacy_vectors_test.go.

package main

import (
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"fmt"

	"github.com/guoyyit/lattice-signature-go/latticesig"
)

const (
	headerLen   = 12
	checksumLen = 4

	kindPublicKey = 1
	kindSecretKey = 2
	kindSignature = 3
)

func main() {
	seed := make([]byte, 32)
	for i := range seed {
		seed[i] = 0x5A + byte(i%7)
	}
	p := latticesig.Toy128

	kp, err := latticesig.GenerateKey(seed, p)
	must(err)

	msg := []byte("legacy v0 message")
	sig, err := latticesig.Sign(kp.Secret, msg)
	must(err)
	tampered := []byte("legacy v0 MESSAGEX")

	// Decode v1 payloads (documented layout) to obtain raw field values.
	pubV1 := payload(kp.Public.MarshalBinary())
	skV1 := payload(kp.Secret.MarshalBinary())
	sigV1 := payload(sig.MarshalBinary())

	aSeed, t := readPubV1(p.N, pubV1)
	skSeed, s, embeddedPub := readSKV1(p.N, skV1)
	ch, z := readSigV1(p.N, sigV1)

	// Parameter-set wire ids are allocated in registration order:
	// toy128 = 0x0001 (see paramsets.go).
	var paramID [2]byte
	binary.BigEndian.PutUint16(paramID[:], 0x0001)

	v0Pub := buildV0(kindPublicKey, paramID[:], func(b []byte) []byte {
		b = append(b, aSeed...)
		b = appendLECoeffs(b, p.Q, t)
		return b
	})
	v0Sig := buildV0(kindSignature, paramID[:], func(b []byte) []byte {
		b = appendLECoeffs(b, p.Q, z)
		b = append(b, ch...)
		return b
	})
	// v0 secret key: embedded public-key blob, then fixed-width seed and s.
	v0SK := buildV0(kindSecretKey, paramID[:], func(b []byte) []byte {
		b = append(b, v0Pub...)
		b = append(b, skSeed...)
		b = appendLECoeffs(b, p.Q, s)
		return b
	})

	fmt.Println("// generated by: go run ./cmd/genlegacyv0 ; do not edit by hand")
	emit("legacyV0SeedHex", seed)
	emit("legacyV0MessageHex", msg)
	emit("legacyV0TamperedMessageHex", tampered)
	emit("legacyV0PublicKeyHex", v0Pub)
	emit("legacyV0SecretKeyHex", v0SK)
	emit("legacyV0SignatureHex", v0Sig)
	_ = embeddedPub
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

func payload(b []byte, err error) []byte {
	must(err)
	plen := binary.BigEndian.Uint32(b[8:])
	return b[headerLen : headerLen+plen]
}

// readPubV1 parses a v1 public-key payload: u16 aSeedLen || aSeed || i16 t.
func readPubV1(n int, b []byte) (aSeed []byte, t []int32) {
	l := int(binary.BigEndian.Uint16(b))
	b = b[2:]
	aSeed = append([]byte(nil), b[:l]...)
	t = readBESigned(b[l:], n)
	return
}

// readSKV1 parses a v1 secret-key payload:
// u16 seedLen || seed || i16 s || u32 pubLen || pubBlob.
func readSKV1(n int, b []byte) (skSeed []byte, s []int32, pubBlob []byte) {
	l := int(binary.BigEndian.Uint16(b))
	b = b[2:]
	skSeed = append([]byte(nil), b[:l]...)
	b = b[l:]
	s = readBESigned(b[:2*n], n)
	b = b[2*n:]
	pl := int(binary.BigEndian.Uint32(b))
	pubBlob = append([]byte(nil), b[4:4+pl]...)
	return
}

// readSigV1 parses a v1 signature payload: ch[32] || i16 z.
func readSigV1(n int, b []byte) (ch []byte, z []int32) {
	ch = append([]byte(nil), b[:32]...)
	z = readBESigned(b[32:], n)
	return
}

func readBESigned(b []byte, n int) []int32 {
	out := make([]int32, n)
	for i := 0; i < n; i++ {
		out[i] = int32(int16(binary.BigEndian.Uint16(b[2*i:])))
	}
	return out
}

// appendLECoeffs appends v0 little-endian unsigned canonical residues in
// [0, q) for each symmetric-range coefficient.
func appendLECoeffs(dst []byte, q int, coeffs []int32) []byte {
	for _, c := range coeffs {
		r := int(c)
		if r < 0 {
			r += q
		}
		var u [2]byte
		binary.LittleEndian.PutUint16(u[:], uint16(r))
		dst = append(dst, u[:]...)
	}
	return dst
}

func buildV0(kind byte, paramID []byte, fill func([]byte) []byte) []byte {
	body := fill(make([]byte, 0))
	total := headerLen + len(body) + checksumLen
	buf := make([]byte, total)
	buf[0], buf[1], buf[2], buf[3] = 'L', 'S', 'G', '1'
	buf[4] = kind
	buf[5] = 0 // historical version 0
	copy(buf[6:], paramID)
	binary.BigEndian.PutUint32(buf[8:], uint32(len(body)))
	copy(buf[headerLen:], body)
	sum := sha256.Sum256(buf[:headerLen+len(body)])
	copy(buf[headerLen+len(body):], sum[:checksumLen])
	return buf
}

func emit(name string, b []byte) {
	fmt.Printf("const %s = \"%s\"\n", name, hex.EncodeToString(b))
}
