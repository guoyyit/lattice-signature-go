// TestV0VectorsParse ensures every fixed v0 sample decodes successfully.
func TestV0VectorsParse(t *testing.T) {
	if _, err := UnmarshalPublicKey(v0PubVector); err != nil {
		t.Fatalf("v0 pub vector: %v", err)
	}
	if _, err := UnmarshalSecretKey(v0SecretVector); err != nil {
		t.Fatalf("v0 secret vector: %v", err)
	}
	if _, err := UnmarshalSignature(v0SigVector); err != nil {
		t.Fatalf("v0 sig vector: %v", err)
	}
}

// TestV0InteropPublicKeyWithCurrentSignature verifies a v0 public key accepts
// a current (v1) signature.
func TestV0InteropPublicKeyWithCurrentSignature(t *testing.T) {
	pk, err := UnmarshalPublicKey(v0PubVector)
	if err != nil { t.Fatal(err) }
	kp, _ := GenerateKey(testSeed(), Toy128)
	msg := []byte("legacy interop message")
	sig, _ := Sign(kp.Secret, msg)
	if err := Verify(pk, msg, sig); err != nil {
		t.Fatalf("v0 pub + v1 sig: %v", err)
	}
}

// TestV0InteropCurrentPublicKeyWithV0Signature verifies a current (v1) public
// key accepts a v0 signature.
func TestV0InteropCurrentPublicKeyWithV0Signature(t *testing.T) {
	kp, _ := GenerateKey(testSeed(), Toy128)
	msg := []byte("legacy interop message")
	if err := VerifyEncoded(kp.Public, msg, v0SigVector); err != nil {
		t.Fatalf("v1 pub + v0 sig: %v", err)
	}
}

// TestV0InteropSecretKeySignsAndVerifies recovers a v0 secret key, signs with
// it, and verifies the result.
func TestV0InteropSecretKeySignsAndVerifies(t *testing.T) {
	sk, err := UnmarshalSecretKey(v0SecretVector)
	if err != nil { t.Fatal(err) }
	pk, err := UnmarshalPublicKey(v0PubVector)
	if err != nil { t.Fatal(err) }
	msg := []byte("legacy interop message")
	sig, err := Sign(sk, msg)
	if err != nil { t.Fatal(err) }
	if err := Verify(pk, msg, sig); err != nil {
		t.Fatalf("v0 secret sign+verify: %v", err)
	}
	// The signature must match the fixed v0 signature vector (determinism).
	sigV0, err := UnmarshalSignature(v0SigVector)
	if err != nil { t.Fatal(err) }
	if !polyEqual(sig.z, sigV0.z) || sig.ch != sigV0.ch {
		t.Fatal("v0 secret produced a different signature than the fixed vector")
	}
}

