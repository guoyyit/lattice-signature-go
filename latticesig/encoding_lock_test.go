// TestCurrentEncodingLocked reproduces the fixed v1 vectors byte-for-byte.
func TestCurrentEncodingLocked(t *testing.T) {
	seed := testSeed()
	p := Toy128
	msg := []byte("legacy interop message")

	kp, err := GenerateKey(seed, p)
	if err != nil { t.Fatal(err) }

	pubV1, err := kp.Public.MarshalBinary()
	if err != nil { t.Fatal(err) }
	if !bytes.Equal(pubV1, v1PubVector) {
		t.Fatal("v1 public key encoding changed")
	}

	skV1, err := kp.Secret.MarshalBinary()
	if err != nil { t.Fatal(err) }
	if !bytes.Equal(skV1, v1SecretVector) {
		t.Fatal("v1 secret key encoding changed")
	}

	sig, err := Sign(kp.Secret, msg)
	if err != nil { t.Fatal(err) }
	sigV1, err := sig.MarshalBinary()
	if err != nil { t.Fatal(err) }
	if !bytes.Equal(sigV1, v1SigVector) {
		t.Fatal("v1 signature encoding changed")
	}

	// The fixed vectors must parse and verify.
	if err := VerifyEncoded(kp.Public, msg, v1SigVector); err != nil {
		t.Fatalf("fixed v1 sig vector: %v", err)
	}
}
